class ManualFinancialReaderTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp=tempfile.TemporaryDirectory(prefix='manual-financial-reader-',dir=HERE)
        cls.addClassCleanup(cls.temp.cleanup)
        cls.binary=Path(cls.temp.name)/'driver'
        cls.compiled=None
        if (NATIVE/'manual_financial_reader_core.hpp').exists():
            cls.compiled=subprocess.run(['/usr/bin/c++','-std=c++11','-Wall','-Wextra','-Werror',
                str(HERE/'manual_financial_reader_driver.cpp'),'-o',str(cls.binary)],capture_output=True,timeout=30)
    def scenario(self,name):
        self.assertIsNotNone(self.compiled,'manual financial observation reader is not implemented')
        self.assertEqual(0,self.compiled.returncode,self.compiled.stderr.decode(errors='replace'))
        r=subprocess.run([str(self.binary),name],capture_output=True,timeout=5)
        self.assertEqual(0,r.returncode,r.stderr.decode(errors='replace'))

for name in SCENARIOS:
    def run(self,name=name):self.scenario(name)
    setattr(ManualFinancialReaderTests,'test_'+name.replace('-','_'),run)

# These SQL tests exercise the emitted statement in a real local relational
# engine. They catch wrong predicates/physical columns, not InnoDB behavior.
class ManualFinancialSQLTests(unittest.TestCase):
    setUpClass=classmethod(ManualFinancialReaderTests.setUpClass.__func__)
    scenario=ManualFinancialReaderTests.scenario
    def database(self):
        db=sqlite3.connect(':memory:')
        self.addCleanup(db.close)
        db.create_function('CONCAT',-1,lambda *args: ''.join(str(x) for x in args))
        columns={
          'account':'id', 'account2project':'account project',
          'subaccount':'id account project currency balance creditlimit allowpostpaid active',
          'currency':'id iso active', 'user':'id account enabled remoteid remotelevel level',
          'payment':'id subaccount paymethod currency status subaccountamount paymethodamount usedamount commissionamount taxrate taxamount billorder invoice recurring recurring_subscription expense_commission sender recipient externalid xmlparams recurring_action_on_fail recurring_action_on_success refund autogenerated chargecommission',
          'paymethod':'id currency active recurring module commissionamount commissionpercent minamount maxamount profiletype xmlparams receipt_profiletype',
          'item':'id account', 'billorder':'id subaccount', 'expense':'id subaccount', 'lineitem':'id subaccount',
          'recurring':'id subaccount paymethod init_payment','recurring_subscription':'id subaccount paymethod',
          'affiliatereward':'payment', 'billorderitem':'commission_for_payment', 'expense2payment':'payment',
          'invoiceitem2payment':'payment', 'payment2payment':'payment_base payment_refund',
          'payment_upload2payment':'payment', 'promotioncoupon2account':'payment',
          'paymethod2company':'paymethod', 'paymethod2group':'paymethod', 'paymethod2project':'paymethod',
          'paymethodparam':'paymethod', 'paymenter_qa_journal_v1':'run_id case_id business_case_id facts_hash'}
        for table,cs in columns.items():
            db.execute('CREATE TABLE '+table+' ('+','.join(c+' TEXT' for c in cs.split())+')')
        def put(table,**values):
            db.execute('INSERT INTO '+table+' ('+','.join(values)+') VALUES ('+','.join('?' for _ in values)+')',tuple(values.values()))
        put('account',id='101');put('account2project',account='101',project='301')
        put('currency',id='401',iso='USD',active='on')
        put('subaccount',id='201',account='101',project='301',currency='401',balance='0.0100',creditlimit='0.0000',allowpostpaid='off',active='on')
        for u in ('801','802'):put('user',id=u,account='101',enabled='off',remotelevel='0',level='29')
        for p in ('1001','1002','1003','1004'):
            put('payment',id=p,subaccount='201',paymethod='501',currency='401',status='4' if p=='1001' else '1',subaccountamount='0.0100',paymethodamount='0.0100',usedamount='0.0000',commissionamount='0.0000',taxrate='0.0000',taxamount='0.0000',refund='off',autogenerated='off',chargecommission='off')
        put('paymethod',id='501',currency='401',active='off',recurring='off',module='pmfixture',commissionamount='0.0000',commissionpercent='0',minamount='0.0000')
        return db
    def sql(self):
        self.assertIsNotNone(self.compiled)
        self.assertEqual(0,self.compiled.returncode,self.compiled.stderr.decode(errors='replace'))
        return subprocess.run([str(self.binary),'emit-query'],capture_output=True,check=True).stdout.decode()
    def validate(self,rows):
        payload=''.join('\t'.join(str(c) for c in row)+'\n' for row in rows).encode()
        return subprocess.run([str(self.binary),'validate-input'],input=payload,capture_output=True).returncode==0
    def test_statement_queries_physical_schema_and_preserves_missing_journal(self):
        with self.database() as db:
            rows=db.execute(self.sql()).fetchall()
            self.assertTrue(self.validate(rows))
            self.assertFalse(any(r[0]=='journal' for r in rows))
    def test_no_financial_cells_from_cross_owned_payment(self):
        with self.database() as db:
            db.execute("UPDATE payment SET subaccount='999' WHERE id='1001'")
            rows=db.execute(self.sql()).fetchall()
            self.assertFalse(any(r[0]=='payment' and r[1]=='1001' for r in rows))
            self.assertFalse(self.validate(rows))
    def test_no_user_cells_from_cross_owned_user(self):
        with self.database() as db:
            db.execute("UPDATE user SET account='999' WHERE id='801'")
            rows=db.execute(self.sql()).fetchall()
            self.assertFalse(any(r[0]=='user' and r[1]=='801' for r in rows))
            self.assertFalse(self.validate(rows))
    def test_no_balance_or_payment_cells_from_cross_owned_subaccount(self):
        with self.database() as db:
            db.execute("UPDATE subaccount SET account='999' WHERE id='201'")
            rows=db.execute(self.sql()).fetchall()
            self.assertFalse(any(r[0] in ('subaccount','payment') for r in rows))
            self.assertFalse(self.validate(rows))
    def test_null_project_is_not_treated_as_owned(self):
        with self.database() as db:
            db.execute("UPDATE account2project SET project=NULL")
            self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
    def test_non_fk_stored_method_reference_is_not_silently_ignored(self):
        with self.database() as db:
            db.execute("INSERT INTO recurring (id,subaccount,paymethod,init_payment) VALUES ('999','999','999','1001')")
            self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
    def test_every_reverse_link_is_rejected(self):
        for table,column in (('affiliatereward','payment'),('billorderitem','commission_for_payment'),('expense2payment','payment'),('invoiceitem2payment','payment'),('payment2payment','payment_base'),('payment2payment','payment_refund'),('payment_upload2payment','payment'),('promotioncoupon2account','payment')):
            with self.subTest(table=table,column=column), self.database() as db:
                db.execute('INSERT INTO '+table+' ('+column+") VALUES ('1001')")
                self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
    def test_bad_decimal_inputs_are_rejected_without_rounding(self):
        for value in ('-0.0000','00.0100','1e-2','0.01','+0.0100','100000000000000.0000','0.00000','nan','.0001','1.000x'):
            with self.subTest(value=value):self.scenario('money-reject:'+value)

    def test_each_stored_payment_link_and_action_is_rejected(self):
        fields=('billorder','invoice','recurring','recurring_subscription','expense_commission','sender','recipient','externalid','xmlparams','recurring_action_on_fail','recurring_action_on_success','refund','autogenerated')
        for field in fields:
            with self.subTest(field=field), self.database() as db:
                db.execute('UPDATE payment SET '+field+"=? WHERE id='1001'",('on' if field in ('refund','autogenerated') else '999',))
                self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
    def test_each_method_secret_or_extra_binding_is_rejected(self):
        for field in ('profiletype','xmlparams','receipt_profiletype'):
            with self.subTest(field=field), self.database() as db:
                db.execute('UPDATE paymethod SET '+field+"='unreturned-sensitive-text'")
                rows=db.execute(self.sql()).fetchall()
                self.assertFalse(self.validate(rows))
                self.assertNotIn('unreturned-sensitive-text',str(rows))
        for table in ('paymethod2company','paymethod2group','paymethod2project','paymethodparam'):
            with self.subTest(table=table), self.database() as db:
                db.execute('INSERT INTO '+table+" (paymethod) VALUES ('501')")
                self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
    def test_extra_owned_rows_and_missing_bindings_are_rejected(self):
        mutations=("INSERT INTO user (id,account) VALUES ('803','101')",
                   "INSERT INTO payment (id,subaccount) VALUES ('1005','201')",
                   "INSERT INTO payment (id,subaccount,paymethod) VALUES ('1005','999','501')",
                   "INSERT INTO subaccount (id,account) VALUES ('202','101')",
                   "INSERT INTO item (id,account) VALUES ('999','101')",
                   "INSERT INTO billorder (id,subaccount) VALUES ('999','201')",
                   "INSERT INTO expense (id,subaccount) VALUES ('999','201')",
                   "INSERT INTO lineitem (id,subaccount) VALUES ('999','201')",
                   "INSERT INTO recurring_subscription (id,subaccount) VALUES ('999','201')",
                   "DELETE FROM account", "DELETE FROM account2project", "DELETE FROM currency")
        for mutation in mutations:
            with self.subTest(mutation=mutation), self.database() as db:
                db.execute(mutation)
                self.assertFalse(self.validate(db.execute(self.sql()).fetchall()))
