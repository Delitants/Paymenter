FIELDS={
 Dataset.ACCOUNTS:('id',),
 Dataset.SUBACCOUNTS:('id','account','project','currency','balance','creditlimit','allowpostpaid','active'),
 Dataset.PAYMENTS:('id','subaccount','paymethod','currency','status','subaccountamount','paymethodamount','usedamount','commissionamount','taxrate','taxamount','createdate','paydate'),
 Dataset.METHODS:('id','module','currency','active','recurring'),
 Dataset.CURRENCIES:('id','iso','active')}
LINKS=('externalid','billorder','invoice','recurring','recurring_subscription','expense_commission','sender','recipient','xmlparams','recurring_action_on_fail','recurring_action_on_success')
BOOLS=('refund','autogenerated','chargecommission')
TABLES={Dataset.ACCOUNTS:('account','a'),Dataset.SUBACCOUNTS:('subaccount','s'),Dataset.PAYMENTS:('payment','p'),Dataset.METHODS:('paymethod','m'),Dataset.CURRENCIES:('currency','c')}

@dataclass(frozen=True)
class Query:
    kind:str
    dataset:Dataset
    sql:str
    params:tuple
    limit:int
    @property
    def digest(self):return hashlib.sha256(canonical([self.kind,self.dataset.value,self.sql,list(self.params),self.limit])).hexdigest()

def fields(dataset):
    names=FIELDS[dataset]
    if dataset==Dataset.PAYMENTS:names+=tuple('link_'+n for n in LINKS)+tuple('flag_'+n for n in BOOLS)
    return names

def _projection(dataset):
    alias=TABLES[dataset][1];parts=[alias+'.`'+n+'`' for n in FIELDS[dataset]]
    if dataset==Dataset.PAYMENTS:
        for n in LINKS:
            parts.append("CASE WHEN p.`%s` IS NULL THEN 'null' WHEN CAST(p.`%s` AS CHAR)='' THEN 'empty' ELSE 'present' END AS `link_%s`"%(n,n,n))
        for n in BOOLS:
            parts.append("CASE WHEN p.`%s` IS NULL THEN 'null' WHEN CAST(p.`%s` AS CHAR)='on' THEN 'on' WHEN CAST(p.`%s` AS CHAR)='off' THEN 'off' ELSE 'invalid' END AS `flag_%s`"%(n,n,n,n))
    return ','.join(parts)

def _scope(dataset,n):
    slots=','.join(['%s']*n)
    owners='s.`account` IN ('+slots+')'
    method='SELECT DISTINCT p.`paymethod` FROM `payment` p JOIN `subaccount` s ON s.`id`=p.`subaccount` WHERE '+owners
    if dataset==Dataset.ACCOUNTS:return 'a.`id` IN ('+slots+')',1
    if dataset==Dataset.SUBACCOUNTS:return owners,1
    if dataset==Dataset.PAYMENTS:return 'p.`subaccount` IN (SELECT s.`id` FROM `subaccount` s WHERE '+owners+')',1
    if dataset==Dataset.METHODS:return 'm.`id` IN ('+method+')',1
    return ('c.`id` IN (SELECT s.`currency` FROM `subaccount` s WHERE '+owners+' UNION SELECT p.`currency` FROM `payment` p JOIN `subaccount` s ON s.`id`=p.`subaccount` WHERE '+owners+' UNION SELECT m.`currency` FROM `paymethod` m WHERE m.`id` IN ('+method+'))'),3

@dataclass(frozen=True)
class QueryPlan:
    account_ids:tuple[str,...]
    profile_hash:str
    def _query(self,dataset,kind,after=None):
        if not isinstance(dataset,Dataset):raise AuditError('query-dataset')
        if after is not None and not positive_id(after):raise AuditError('query-cursor')
        table,alias=TABLES[dataset];scope,repeats=_scope(dataset,len(self.account_ids));params=self.account_ids*repeats
        projection='COUNT('+alias+'.`id`) AS `count`' if kind=='count' else _projection(dataset)
        sql='SELECT '+projection+' FROM `'+table+'` '+alias+' WHERE '+scope
        if kind=='page':
            if after is not None:sql+=' AND '+alias+'.`id` > %s';params+=(after,)
            sql+=' ORDER BY '+alias+'.`id` LIMIT %s';params+=(256,)
        return Query(kind,dataset,sql,params,256 if kind=='page' else 1)
    def count(self,dataset):return self._query(dataset,'count')
    def page(self,dataset,after_id):return self._query(dataset,'page',after_id)

# Bind actual rendered templates, including CASE, scopes, aliases and pagination.
def _template_hash():
    p=QueryPlan(('1','2'),'')
    return hashlib.sha256(canonical([(q.sql,q.kind,q.dataset.value) for d in Dataset for q in (p.count(d),p.page(d,None),p.page(d,'1'))])).hexdigest()
PROFILE_QUERY_HASH=_template_hash()
def fictional_profile():return Profile('fictional-v1','fictional','a'*64,PROFILE_QUERY_HASH,'c'*64)
def build_plan(descriptor,profile):
    if profile!=fictional_profile() or descriptor.query_profile_hash!=PROFILE_QUERY_HASH or descriptor.server_profile_hash!=profile.server_hash or descriptor.schema_hash!=profile.schema_hash:raise AuditError('query-profile')
    if not descriptor.account_ids or len(descriptor.account_ids)>2048 or not all(positive_id(n) for n in descriptor.account_ids) or descriptor.account_ids!=tuple(sorted(set(descriptor.account_ids),key=int)):raise AuditError('query-cohort')
    return QueryPlan(descriptor.account_ids,PROFILE_QUERY_HASH)
